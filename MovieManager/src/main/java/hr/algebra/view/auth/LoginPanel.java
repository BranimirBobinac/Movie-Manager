    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        if (!formValid()) {
            return;
        }

        String username = tfLoginUsername.getText().trim();
        String plainPassword = new String(pfLoginPassword.getPassword());

        try {
            repository = RepositoryFactory.getUserRepository();
            Optional<User> userOpt = repository.loginUser(username);

            if (userOpt.isEmpty()) {
                MessageUtils.showErrorMessage("Login", "User not found.");
                return;
            }

            User user = userOpt.get();
            if (!passwordMatches(plainPassword, user)) {
                MessageUtils.showErrorMessage("Login", "Incorrect password.");
                pfLoginPassword.setText("");
                return;
            }

            JOptionPane.showMessageDialog(btnLogin, "Login successful. Welcome, " + user.getUsername());
            clearForm();

            if (user.getRole() == Role.ADMIN) {
                movieManager.unlockApplication();
            } else {
                movieManager.unlockUserView();
            }

        } catch (Exception e) {
            Logger.getLogger(LoginPanel.class.getName()).log(Level.SEVERE, null, e);
            MessageUtils.showErrorMessage("Login", "Login failed: " + e.getMessage());
        }
    }//GEN-LAST:event_btnLoginActionPerformed



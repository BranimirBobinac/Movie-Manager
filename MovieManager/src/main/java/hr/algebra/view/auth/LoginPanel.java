    private void init() {
        try {
            initValidation();
            hideErrors();
        } catch (Exception ex) {
            Logger.getLogger(LoginPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Unrecoverable error", "Cannot initiate the form.");
            System.exit(1);
        }
    }

    private List<JTextComponent> validationFields;
    private List<JLabel> errorLabels;

    private void initValidation() {
        validationFields = Arrays.asList(
                tfLoginUsername,
                pfLoginPassword
        );
        errorLabels = Arrays.asList(
                lbLoginUsernameError,
                lbLoginPasswordError
        );
    }

    private void hideErrors() {
        errorLabels.forEach(e -> e.setVisible(false));
    }

    private boolean formValid() {
        if (validationFields == null) {
            initValidation();
        }
        hideErrors();
        boolean ok = true;
        for (int i = 0; i < validationFields.size(); i++) {
            boolean empty = validationFields.get(i).getText().trim().isEmpty();
            ok &= !empty;
            errorLabels.get(i).setVisible(empty);
        }
        return ok;
    }

    private void clearForm() {
        tfLoginUsername.setText("");
        pfLoginPassword.setText("");
        hideErrors();
    }

    private static boolean passwordMatches(String plainPassword, User user) {
        String stored = user.getPassword();
        if (stored == null || !stored.startsWith("$2")) {
            return false;
        }
        try {
            // BCrypt hash vec sadrzi salt, checkpw radi usporedbu sigurno
            return BCrypt.checkpw(plainPassword, stored);
        } catch (IllegalArgumentException e) {
            return false;
        }
    }
